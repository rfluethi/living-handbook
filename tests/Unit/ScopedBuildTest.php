<?php
/**
 * The release build leaves no shared name behind after PHP-Scoper.
 *
 * bin/verify-vendor-prefix.php was green for 0.75.0, and the zip still
 * collided with other plugins in three places, all of them outside what
 * PHP-Scoper touches or decides:
 *
 * - Composer's dump-autoload adds 'Composer\InstalledVersions' to the
 *   classmap, pointing at a file that by then declares the prefixed class. The
 *   second class_exists() on the plain name, from any plugin, ended in "Cannot
 *   declare class".
 * - The "files" autoloads are keyed by md5(package:path), the same key in
 *   every Composer project, so another plugin with
 *   symfony/deprecation-contracts made Composer skip this plugin's scoped copy.
 * - symfony/yaml calls trigger_deprecation() unqualified inside its namespace,
 *   which PHP-Scoper leaves alone, so the call went nowhere.
 *
 * The full proof is the build itself: bin/build.sh runs the extended
 * verify-vendor-prefix.php against the real scoped tree. These tests hold the
 * pieces in place without needing PHP-Scoper or the network: the patcher, the
 * script that rewrites the generated autoloader, and the build steps that call
 * them.
 *
 * @package LivingHandbook
 */

declare( strict_types=1 );

namespace LivingHandbook\Tests\Unit;

use PHPUnit\Framework\TestCase;

/**
 * scoper.inc.php, bin/finish-scoped-autoload.php and bin/build.sh.
 */
final class ScopedBuildTest extends TestCase {

	private const PREFIX = 'LivingHandbook\\Vendor';

	/**
	 * Temporary plugin tree of the current test.
	 *
	 * @var string
	 */
	private string $tree = '';

	/**
	 * Remove the temporary tree.
	 *
	 * @return void
	 */
	protected function tearDown(): void {
		if ( '' !== $this->tree && is_dir( $this->tree ) ) {
			$it = new \RecursiveIteratorIterator(
				new \RecursiveDirectoryIterator( $this->tree, \FilesystemIterator::SKIP_DOTS ),
				\RecursiveIteratorIterator::CHILD_FIRST
			);
			foreach ( $it as $item ) {
				$item->isDir() ? rmdir( $item->getPathname() ) : unlink( $item->getPathname() );
			}
			rmdir( $this->tree );
		}
		parent::tearDown();
	}

	/**
	 * A file from the plugin root.
	 *
	 * @param string $relative Path relative to the plugin root.
	 * @return string
	 */
	private function source( string $relative ): string {
		$path = dirname( __DIR__, 2 ) . '/' . $relative;
		$this->assertFileExists( $path );

		return (string) file_get_contents( $path );
	}

	/**
	 * Run the patchers of scoper.inc.php over a piece of code.
	 *
	 * @param string $code PHP source as PHP-Scoper would hand it over.
	 * @return string
	 */
	private function patch( string $code ): string {
		$config = require dirname( __DIR__, 2 ) . '/scoper.inc.php';
		$this->assertArrayHasKey( 'patchers', $config, 'scoper.inc.php has no patchers.' );

		foreach ( $config['patchers'] as $patcher ) {
			$code = $patcher( 'vendor/symfony/yaml/Parser.php', self::PREFIX, $code );
		}

		return $code;
	}

	/**
	 * The unqualified call in a namespace gets the prefixed function; nothing
	 * that only resembles it is touched.
	 *
	 * @return void
	 */
	public function test_the_patcher_qualifies_only_the_unqualified_calls(): void {
		$this->assertSame(
			"namespace LivingHandbook\\Vendor\\Symfony\\Component\\Yaml;\n\\LivingHandbook\\Vendor\\trigger_deprecation('symfony/yaml', '6.2', 'x');",
			$this->patch( "namespace LivingHandbook\\Vendor\\Symfony\\Component\\Yaml;\ntrigger_deprecation('symfony/yaml', '6.2', 'x');" )
		);

		$untouched = array(
			// Already qualified by PHP-Scoper.
			"\\LivingHandbook\\Vendor\\trigger_deprecation('a', '1', 'b');",
			// The definition in deprecation-contracts.
			'function trigger_deprecation(string $package, string $version, string $message): void {}',
			// Methods and longer names.
			'$this->trigger_deprecation(1); Foo::trigger_deprecation(1); my_trigger_deprecation(1);',
			// The guard around the definition.
			"if (!\\function_exists('LivingHandbook\\Vendor\\trigger_deprecation')) {}",
		);
		foreach ( $untouched as $code ) {
			$this->assertSame( $code, $this->patch( $code ) );
		}
	}

	/**
	 * Write a vendor/composer directory as dump-autoload leaves it in a scoped
	 * tree, with the two shared names in it.
	 *
	 * @return array<string, string> The identifiers Composer used.
	 */
	private function make_generated_autoloader(): array {
		$this->tree = sys_get_temp_dir() . '/lh-scoped-' . bin2hex( random_bytes( 4 ) );
		mkdir( $this->tree . '/vendor/composer', 0777, true );

		$ids = array(
			'symfony/deprecation-contracts/function.php' => md5( 'symfony/deprecation-contracts:function.php' ),
			'symfony/polyfill-ctype/bootstrap.php'       => md5( 'symfony/polyfill-ctype:bootstrap.php' ),
		);

		$classmap  = "<?php\n\n// autoload_classmap.php @generated by Composer\n\n\$vendorDir = dirname(__DIR__);\n\$baseDir = dirname(\$vendorDir);\n\nreturn array(\n";
		$classmap .= "    'Composer\\\\InstalledVersions' => \$vendorDir . '/composer/InstalledVersions.php',\n";
		$classmap .= "    'LivingHandbook\\\\Vendor\\\\Symfony\\\\Component\\\\Yaml\\\\Yaml' => \$vendorDir . '/symfony/yaml/Yaml.php',\n";
		$classmap .= ");\n";
		file_put_contents( $this->tree . '/vendor/composer/autoload_classmap.php', $classmap );

		$files = "<?php\n\nreturn array(\n";
		foreach ( $ids as $path => $id ) {
			$files .= "    '{$id}' => \$vendorDir . '/{$path}',\n";
		}
		$files .= ");\n";
		file_put_contents( $this->tree . '/vendor/composer/autoload_files.php', $files );

		$static = "<?php\n\nclass ComposerStaticInitTest\n{\n    public static \$files = array (\n";
		foreach ( $ids as $path => $id ) {
			$static .= "        '{$id}' => __DIR__ . '/..' . '/{$path}',\n";
		}
		$static .= "    );\n\n    public static \$classMap = array (\n";
		$static .= "        'Composer\\\\InstalledVersions' => __DIR__ . '/..' . '/composer/InstalledVersions.php',\n";
		$static .= "        'LivingHandbook\\\\Vendor\\\\Symfony\\\\Component\\\\Yaml\\\\Yaml' => __DIR__ . '/..' . '/symfony/yaml/Yaml.php',\n";
		$static .= "    );\n}\n";
		file_put_contents( $this->tree . '/vendor/composer/autoload_static.php', $static );

		file_put_contents( $this->tree . '/vendor/composer/InstalledVersions.php', "<?php\nnamespace LivingHandbook\\Vendor\\Composer;\nclass InstalledVersions {}\n" );

		return $ids;
	}

	/**
	 * Run bin/finish-scoped-autoload.php over the tree.
	 *
	 * @return int Exit status.
	 */
	private function finish(): int {
		$script = dirname( __DIR__, 2 ) . '/bin/finish-scoped-autoload.php';
		$this->assertFileExists( $script );

		$output = array();
		$status = 0;
		exec( escapeshellarg( PHP_BINARY ) . ' ' . escapeshellarg( $script ) . ' ' . escapeshellarg( $this->tree ) . ' ' . escapeshellarg( self::PREFIX ) . ' 2>&1', $output, $status );

		return $status;
	}

	/**
	 * Composer's own class leaves the classmap, under the plain name, in both
	 * files that carry it. The prefixed entries stay.
	 *
	 * @return void
	 */
	public function test_the_unprefixed_installed_versions_entry_is_removed(): void {
		$this->make_generated_autoloader();

		$this->assertSame( 0, $this->finish() );

		foreach ( array( 'autoload_classmap.php', 'autoload_static.php' ) as $file ) {
			$source = (string) file_get_contents( $this->tree . '/vendor/composer/' . $file );
			$this->assertStringNotContainsString( "'Composer\\\\InstalledVersions'", $source, $file );
			$this->assertStringContainsString( "'LivingHandbook\\\\Vendor\\\\Symfony\\\\Component\\\\Yaml\\\\Yaml'", $source, $file );
		}
		$this->assertFileDoesNotExist( $this->tree . '/vendor/composer/InstalledVersions.php' );
	}

	/**
	 * The "files" keys no longer match what another Composer project uses for
	 * the same package, and both files that list them agree on the new ones.
	 *
	 * @return void
	 */
	public function test_the_files_identifiers_are_made_the_plugins_own(): void {
		$ids = $this->make_generated_autoloader();

		$this->assertSame( 0, $this->finish() );

		$static = (string) file_get_contents( $this->tree . '/vendor/composer/autoload_static.php' );
		$files  = (string) file_get_contents( $this->tree . '/vendor/composer/autoload_files.php' );
		foreach ( $ids as $path => $shared ) {
			$this->assertStringNotContainsString( $shared, $static, $path . ' still uses the shared key.' );
			$this->assertStringNotContainsString( $shared, $files, $path . ' still uses the shared key.' );

			$own = md5( self::PREFIX . ':' . $path );
			$this->assertStringContainsString( "'{$own}' => __DIR__ . '/..' . '/{$path}'", $static );
			$this->assertStringContainsString( "'{$own}' => \$vendorDir . '/{$path}'", $files );
		}

		// A second run finds nothing left to do and changes nothing.
		$this->assertSame( 0, $this->finish() );
		$this->assertSame( $static, (string) file_get_contents( $this->tree . '/vendor/composer/autoload_static.php' ) );
	}

	/**
	 * The build runs the step, after dump-autoload and before the check, pins
	 * dist installs, and strips the libraries' development files before the
	 * scoper sees them.
	 *
	 * @return void
	 */
	public function test_the_build_runs_every_step_in_order(): void {
		$build = $this->source( 'bin/build.sh' );

		$this->assertMatchesRegularExpression( '/composer install --no-dev --prefer-dist /', $build );

		$strip   = strpos( $build, 'rm -rf "${dest}/vendor/bin"' );
		$scoper  = strpos( $build, 'add-prefix' );
		$dump    = strpos( $build, 'composer dump-autoload' );
		$finish  = strpos( $build, 'bin/finish-scoped-autoload.php' );
		$verify  = strpos( $build, 'bin/verify-vendor-prefix.php' );
		$archive = strpos( $build, 'zip -rq' );

		$this->assertIsInt( $strip, 'vendor/bin is not removed.' );
		$this->assertIsInt( $finish, 'The generated autoloader is not finished.' );
		$this->assertLessThan( $scoper, $strip, 'Development files have to go before the scoper reads them.' );
		$this->assertLessThan( $finish, $dump );
		$this->assertLessThan( $verify, $finish );
		$this->assertLessThan( $archive, $verify );

		foreach ( array( '-name tests', '-name Tests', '-name docs', "-iname '*.md'" ) as $pattern ) {
			$this->assertStringContainsString( $pattern, $build );
		}
	}

	/**
	 * The check covers the three cases, so a regression fails the build rather
	 * than a site.
	 *
	 * @return void
	 */
	public function test_the_verification_covers_the_three_collisions(): void {
		$verify = $this->source( 'bin/verify-vendor-prefix.php' );

		$this->assertStringContainsString( 'Composer\\\\InstalledVersions', $verify );
		$this->assertStringContainsString( '__composer_autoload_files', $verify );
		$this->assertStringContainsString( "PREFIX . 'trigger_deprecation'", $verify );
		$this->assertStringContainsString( '!php/const:', $verify );
	}
}
